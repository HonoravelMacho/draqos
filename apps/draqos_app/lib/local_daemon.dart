import 'dart:convert';
import 'dart:io';

import 'package:draqos_client/draqos_client.dart';
import 'package:draqos_core/draqos_core.dart';

/// Manages a LOCAL draqosd process (desktop only).
/// Android never uses this: it is purely a client/editor.
class LocalDaemon {
  Process? _proc;
  final int port;
  LocalDaemon({this.port = 8471});

  static String defaultDataDir() {
    if (Platform.isWindows) {
      final appData = Platform.environment['APPDATA'] ?? '.';
      return '$appData\\draqosd';
    }
    final home = Platform.environment['HOME'] ?? '.';
    return '$home/.local/share/draqosd';
  }

  /// Token previously generated by the local daemon (same data dir).
  static Future<String?> readLocalToken([String? dataDir]) async {
    try {
      final f = File('${dataDir ?? defaultDataDir()}/admin_token');
      if (!await f.exists()) return null;
      final t = (await f.readAsString()).trim();
      return t.isEmpty ? null : t;
    } catch (_) {
      return null;
    }
  }

  bool get running => _proc != null;

  /// Start `draqosd` from PATH (installed) or [exePath].
  Future<void> start({String? exePath}) async {
    if (_proc != null) return;
    final exe = exePath ?? 'draqosd';
    _proc = await Process.start(exe, ['--port', '$port']);
    // Give it a moment; caller probes /api/status.
    await Future<void>.delayed(const Duration(seconds: 1));
    if (_proc == null) throw const ProcessException('draqosd', []);
  }

  Future<void> stop() async {
    final p = _proc;
    _proc = null;
    if (p == null) return;
    p.kill();
    await p.exitCode.timeout(
      const Duration(seconds: 3),
      onTimeout: () {
        p.kill(ProcessSignal.sigkill);
        return -1;
      },
    );
  }

  /// Probe a (local or remote) daemon status.
  static Future<DaemonStatus?> probeStatus(String baseUrl, String token) async {
    final client = DraqosClient(baseUrl: baseUrl, token: token);
    try {
      return await client.status();
    } catch (_) {
      return null;
    } finally {
      client.close();
    }
  }

  /// Build the pairing payload the Android editor scans:
  /// tailnet base URL + local admin token.
  static Future<PairingPayload?> buildPairingPayload({int port = 8471}) async {
    final token = await readLocalToken();
    if (token == null) return null;
    final status = await probeStatus('http://127.0.0.1:$port', token);
    final dns = status?.hostname;
    if (status == null || dns == null || dns.isEmpty) return null;
    final tailnet = status.tailnet;
    final base = tailnet.isEmpty ? 'https://$dns' : 'https://$dns.$tailnet';
    return PairingPayload(baseUrl: base, token: token, machine: dns);
  }

  static String encodePretty(PairingPayload p) =>
      const JsonEncoder.withIndent('  ').convert({
        'baseUrl': p.baseUrl,
        'machine': p.machine,
        'token': '${p.token.substring(0, 8)}…(hidden)',
      });
}
